  // draw → canvas. opts: { size (px, default 64), recolor: {key: "#hex"} }
  function draw(name, opts) {
    const ic = I[name]; if (!ic) return null;
    const o = opts || {}, S = o.size || 64, N = 16, u = S / N;
    const pal = Object.assign({}, ic.p, o.recolor || {});
    const cv = document.createElement("canvas"); cv.width = cv.height = S;
    const x = cv.getContext("2d");
    const on = (r, c) => r >= 0 && r < N && c >= 0 && c < N && ic.g[r][c] !== ".";
    // outline: empty cells that touch a filled one
    x.fillStyle = OUT;
    for (let r = 0; r < N; r++) for (let c = 0; c < N; c++) {
      if (on(r, c)) continue;
      if (on(r - 1, c) || on(r + 1, c) || on(r, c - 1) || on(r, c + 1)) x.fillRect(c * u, r * u, u, u);
    }
    for (let r = 0; r < N; r++) for (let c = 0; c < N; c++) {
      const k = ic.g[r][c]; if (k === ".") continue;
      x.fillStyle = pal[k] || "#ff00ff"; x.fillRect(c * u, r * u, u, u);
    }
    return cv;
  }
